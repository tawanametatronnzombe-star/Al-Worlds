// Minimal, honest service worker: network-first, with a small cache as a
// fallback only if the network genuinely fails (e.g. briefly offline).
// This is what PWABuilder's "Has Service Worker" check is looking for —
// no fake offline claims, just real request handling.

const CACHE_NAME = 'ai-worlds-v1';

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(names.filter((n) => n !== CACHE_NAME).map((n) => caches.delete(n)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return; // don't cache POSTs/API calls

  event.respondWith(
    fetch(event.request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});
